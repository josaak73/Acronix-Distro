#!/usr/bin/env bash
# Splits sources/logoUNI.jpg into one transparent PNG per logo piece, plus a
# glow sprite and progress bar, and builds theme/acronix/acronix.script from
# theme/acronix.script.in with the final piece positions prepended (the
# Plymouth script language has no "include", so everything lives in one file).
#
# How it works:
#   1. threshold the JPG into a black/white mask and label its connected shapes
#   2. for each shape, keep only that label (ImageMagick writes the label id as
#      the pixel value, so -threshold 0 turns it back into white), dilate it a little so the soft
#      JPEG edge is included, and use the original darkness as the alpha channel
#      (this keeps the anti-aliased edges instead of a jagged threshold)
#   3. crop to the shape's bounding box and paint it white
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/sources/logoUNI.jpg"
OUT="$ROOT/theme/acronix"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

mkdir -p "$OUT"

# The source photo is rotated by about half a degree (its vertical edges drift
# ~2 px over 240 px). Rotate it back so the assembled logo sits straight.
DESKEW_DEG=0.45
magick "$SRC" -background white -rotate "$DESKEW_DEG" +repage "$WORK/straight.png"
SRC="$WORK/straight.png"

# Black/white mask: logo = white, background = black
magick "$SRC" -colorspace Gray -threshold 60% -negate "$WORK/mask.png"

# Darkness of the original = alpha (255 where the logo is solid blue)
magick "$SRC" -colorspace Gray -negate -level 15%,70% "$WORK/alpha.png"

# Label shapes; ignore specks smaller than 200 px
magick "$WORK/mask.png" \
    -define connected-components:verbose=true \
    -define connected-components:area-threshold=200 \
    -connected-components 8 null: 2>&1 \
    | awk '/gray\(255\)/ {print}' > "$WORK/components.txt"

# Pieces are named by size/position below: u = left block, n = large middle
# shape with the right stem, dot = small square on top of the I
mapfile -t rows < <(
    awk '{
        id=$1; sub(":","",id); split($2,b,/[x+]/);
        print id, b[1], b[2], b[3], b[4], $4
    }' "$WORK/components.txt"
)

: > "$OUT/layout.script"
echo "# generated by scripts/make_assets.sh. Edit theme/acronix.script.in instead." >> "$OUT/layout.script"

# find the whole-logo bounding box to use as the layout origin
minx=99999; miny=99999; maxx=0; maxy=0
for r in "${rows[@]}"; do
    read -r id w h x y area <<< "$r"
    (( x < minx )) && minx=$x
    (( y < miny )) && miny=$y
    (( x + w > maxx )) && maxx=$((x + w))
    (( y + h > maxy )) && maxy=$((y + h))
done
echo "LOGO_W = $((maxx - minx));" >> "$OUT/layout.script"
echo "LOGO_H = $((maxy - miny));" >> "$OUT/layout.script"

mask_args=()
for r in "${rows[@]}"; do
    read -r id w h x y area <<< "$r"
    if   (( area < 10000 )); then name=dot
    elif (( x < 150 ));       then name=u
    else                           name=n
    fi

    magick "$WORK/mask.png" \
        -define connected-components:keep="$id" \
        -connected-components 8 \
        -threshold 0 \
        -morphology Dilate Disk:2 \
        "$WORK/keep_$name.png"

    magick "$WORK/alpha.png" "$WORK/keep_$name.png" \
        -compose Multiply -composite \
        -crop "$((w + 8))x$((h + 8))+$((x - 4))+$((y - 4))" +repage \
        "$WORK/a_$name.png"

    # white image whose opacity is the darkness crop
    magick "$WORK/a_$name.png" \
        \( +clone -fill white -colorize 100 \) +swap \
        -alpha off -compose CopyOpacity -composite \
        "$OUT/piece_$name.png"

    {
        echo "PIECE_${name^^}_X = $((x - 4 - minx));"
        echo "PIECE_${name^^}_Y = $((y - 4 - miny));"
    } >> "$OUT/layout.script"

    # where this piece lands on the assembled-logo canvas used for the shine
    mask_args+=( "$OUT/piece_$name.png" -geometry "+$((x - minx))+$((y - miny))" -composite )
done

LW=$((maxx - minx)); LH=$((maxy - miny))

# ---- shine sweep ----------------------------------------------------------
# Plymouth scripts cannot clip one image by another, so the glint is
# pre-rendered: the whole logo's silhouette, tinted gold where a slanted band
# crosses it, one PNG per band position. The script plays them in order.
# (The logo is white, so the glint is gold to be visible on it.)
SHINE_FRAMES=14
CW=$((LW + 8)); CH=$((LH + 8))
magick -size "${CW}x${CH}" xc:none "${mask_args[@]}" "$WORK/silhouette.png"
for k in $(seq 0 $((SHINE_FRAMES - 1))); do
    # band centre travels from left of the logo to right of it (slanted by y*0.5)
    centre=$(( -CH / 2 + k * (CW + CH) / (SHINE_FRAMES - 1) ))
    magick -size "${CW}x${CH}" xc:'#FFC93C' \
        \( -size "${CW}x${CH}" xc: -colorspace Gray \
           -fx "max(0, 1 - abs((i + j*0.5) - $centre) / 60)" \) \
        -alpha off -compose CopyOpacity -composite \
        "$WORK/silhouette.png" -compose DstIn -composite \
        "$OUT/shine_$k.png"
done
echo "SHINE_FRAMES = $SHINE_FRAMES;" >> "$OUT/layout.script"

# ---- speed lines ----------------------------------------------------------
# Manga-style streaks radiating from the centre, thin near the middle and wider
# outward. Two different sets so the script can flicker between them.
make_lines() {   # $1 = seed, $2 = output
    local -a polys draw=()
    mapfile -t polys < <(awk -v seed="$1" 'BEGIN {
        srand(seed); cx = 640; cy = 360
        for (i = 0; i < 80; i++) {
            a = rand() * 6.2832; w = 0.010 + rand() * 0.035; r0 = 190 + rand() * 170; r1 = 820
            printf "polygon %.1f,%.1f %.1f,%.1f %.1f,%.1f\n", \
                cx + r0*cos(a), cy + r0*sin(a), \
                cx + r1*cos(a-w), cy + r1*sin(a-w), cx + r1*cos(a+w), cy + r1*sin(a+w)
        }
    }')
    for p in "${polys[@]}"; do draw+=( -draw "$p" ); done
    magick -size 1280x720 xc:none -fill 'rgba(255,255,255,0.55)' "${draw[@]}" \
        -blur 0x0.7 "$2"
}
make_lines 7  "$OUT/lines_a.png"
make_lines 23 "$OUT/lines_b.png"

# ---- comic burst ----------------------------------------------------------
# Spiky starburst: yellow with a red outline and a paler yellow core.
make_burst() {   # $1 = radius scale; prints one polygon primitive
    awk -v k="$1" 'BEGIN {
        srand(5); n = 18; printf "polygon "
        for (i = 0; i < 2 * n; i++) {
            ang = i * 3.14159265 / n
            r = (i % 2 == 0) ? (255 + rand() * 40) * k : 150 * k
            printf "%.1f,%.1f ", 300 + r*cos(ang), 300 + r*sin(ang)
        }
    }'
}
outer=$(make_burst 1.0 ); inner=$(make_burst 0.62)
magick -size 600x600 xc:none \
    -fill '#E4002B' -stroke '#E4002B' -strokewidth 18 -draw "$outer" \
    -fill '#FFD500' -stroke none -draw "$outer" \
    -fill '#FFF3A0' -draw "$inner" \
    "$OUT/burst.png"

# White square the script stretches over the whole screen for the impact flash
magick -size 8x8 xc:white "$OUT/flash.png"

# Cool glow used for the pulse after assembly (a yellow one turned muddy brown on the purple)
magick -size 700x500 xc:none -fill '#8FD3FF' \
    -draw 'ellipse 350,250 230,150 0,360' -blur 0x60 "$OUT/glow.png"

# ---- title letters --------------------------------------------------------
# Each letter of the project name is its own PNG so the script can drop them in
# one by one. Style (bottom to top): soft drop shadow, dark outline, white ring,
# gradient fill, glossy highlight on the upper half. Pre-rendering means the
# boot screen needs no fonts at all for these.
FONT="${FONT:-/usr/share/fonts/noto/NotoSans-Black.ttf}"
FONT_ITALIC="${FONT_ITALIC:-/usr/share/fonts/noto/NotoSans-BlackItalic.ttf}"
for f in "$FONT" "$FONT_ITALIC"; do
    [[ -f "$f" ]] || { echo "Font not found: $f (set FONT / FONT_ITALIC)" >&2; exit 1; }
done

TITLE="ACRONIXOS"
RED_FROM=7             # letters from this index on (the "OS") use the red style
PT=230                 # font size used for rendering
CAPH=176               # every letter is centred in a canvas this tall (+ padding)
PAD=40                 # room around the letter for outline and shadow
GAP=6                  # extra space between neighbouring letters

# solid colour shaped by a grey mask (white = opaque): $1 colour, $2 mask, $3 out
tint() { magick -size "${W}x${H}" xc:"$1" "$2" -alpha off -compose CopyOpacity -composite "$3"; }

make_letter() {   # $1 = char, $2 = output, $3 = fill top colour, $4 = fill bottom colour
    local txt="$WORK/l_txt.png"
    magick -background none -fill white -font "$FONT" -pointsize "$PT" label:"$1" \
        -trim +repage "$txt"
    local tw; tw=$(magick identify -format %w "$txt")
    W=$((tw + 2 * PAD)); H=$((CAPH + 2 * PAD))
    magick "$txt" -background none -gravity center -extent "${W}x${H}" \
        -alpha extract "$WORK/l_mask.png"

    magick "$WORK/l_mask.png" -morphology Dilate Disk:13 -blur 0x1 "$WORK/l_outline.png"
    magick "$WORK/l_mask.png" -morphology Dilate Disk:7  -blur 0x0.6 "$WORK/l_ring.png"
    magick "$WORK/l_outline.png" -roll +9+13 -blur 0x5 -evaluate Multiply 0.55 "$WORK/l_shadow.png"
    # gradient clipped to the letter
    magick -size "${W}x${H}" gradient:"$3-$4" "$WORK/l_grad.png"
    magick "$WORK/l_grad.png" "$WORK/l_mask.png" -alpha off -compose CopyOpacity -composite \
        "$WORK/l_fill.png"
    # gloss: white fading out from the top to the middle of the letter, only inside it
    magick -size "${W}x${H}" gradient:white-black -level 55%,100% -evaluate Multiply 0.55 \
        "$WORK/l_mask.png" -compose Multiply -composite "$WORK/l_gloss_mask.png"
    tint white "$WORK/l_gloss_mask.png" "$WORK/l_gloss.png"

    tint black   "$WORK/l_shadow.png"  "$WORK/l_c_shadow.png"
    tint '#14123F' "$WORK/l_outline.png" "$WORK/l_c_outline.png"
    tint white   "$WORK/l_ring.png"    "$WORK/l_c_ring.png"
    magick -size "${W}x${H}" xc:none \
        "$WORK/l_c_shadow.png" -composite "$WORK/l_c_outline.png" -composite \
        "$WORK/l_c_ring.png" -composite "$WORK/l_fill.png" -composite \
        "$WORK/l_gloss.png" -composite "$2"
}

title_total=0
echo "TITLE_N = ${#TITLE};"       >> "$OUT/layout.script"
echo "TITLE_PAD = $PAD;"          >> "$OUT/layout.script"
for ((i = 0; i < ${#TITLE}; i++)); do
    if (( i < RED_FROM )); then top='#FFF7A8'; bot='#FFB000'
    else                        top='#FFA3B0'; bot='#E6002B'
    fi
    make_letter "${TITLE:i:1}" "$OUT/title_$i.png" "$top" "$bot"
    # distance to the next letter's left edge = visible width + gap
    adv=$((W - 2 * PAD + GAP))
    echo "TITLE_ADV[$i] = $adv;" >> "$OUT/layout.script"
    title_total=$((title_total + adv))
done
echo "TITLE_TOTAL = $title_total;" >> "$OUT/layout.script"
echo "TITLE_IMG_H = $H;"           >> "$OUT/layout.script"

# ---- group badge ----------------------------------------------------------
# A slanted red plate (dark outline, white ring) like a player tag: small yellow
# "PROYECTO DEL GRUPO" on top of a big white group name.
BW=900; BH=250
plate="polygon 60,30 880,30 840,205 20,205"
magick -size "${BW}x${BH}" xc:black -fill white -draw "$plate" "$WORK/b_mask.png"
W=$BW; H=$BH
magick "$WORK/b_mask.png" -morphology Dilate Disk:12 -blur 0x1 "$WORK/b_outline.png"
magick "$WORK/b_mask.png" -morphology Dilate Disk:6  -blur 0x0.6 "$WORK/b_ring.png"
magick "$WORK/b_outline.png" -roll +8+12 -blur 0x5 -evaluate Multiply 0.55 "$WORK/b_shadow.png"
magick -size "${BW}x${BH}" gradient:'#FF4B5C-#B0001E' "$WORK/b_mask.png" \
    -alpha off -compose CopyOpacity -composite "$WORK/b_fill.png"
tint black     "$WORK/b_shadow.png"  "$WORK/b_c_shadow.png"
tint '#14123F' "$WORK/b_outline.png" "$WORK/b_c_outline.png"
tint white     "$WORK/b_ring.png"    "$WORK/b_c_ring.png"
magick -size "${BW}x${BH}" xc:none \
    "$WORK/b_c_shadow.png" -composite "$WORK/b_c_outline.png" -composite \
    "$WORK/b_c_ring.png" -composite "$WORK/b_fill.png" -composite \
    -gravity center -font "$FONT_ITALIC" \
    -stroke '#14123F' -strokewidth 9 -fill '#14123F' \
        -pointsize 44  -annotate +0-50 "PROYECTO DEL GRUPO" \
        -pointsize 112 -annotate +0+24 "4T4-COM-S" \
    -stroke none \
    -fill '#FFE14D' -pointsize 44  -annotate +0-50 "PROYECTO DEL GRUPO" \
    -fill white     -pointsize 112 -annotate +0+24 "4T4-COM-S" \
    "$OUT/badge.png"

# 8x8 square, scaled at runtime into the progress bar
magick -size 8x8 xc:'#FFD500' "$OUT/bar.png"

cat "$OUT/layout.script" "$ROOT/theme/acronix.script.in" > "$OUT/acronix.script"
rm "$OUT/layout.script"

echo "Assets written to $OUT"
